// Helper functions
export function getTotalQuestionsOVIQ4(): number {
  return OVIQ4_CHAPTERS.reduce((total, chapter) => total + chapter.questions.length, 0);
}

export function getCriticalQuestionsOVIQ4(): OVIQQuestion[] {
  return OVIQ4_CHAPTERS.flatMap(chapter => 
    chapter.questions.filter(q => q.priority === 'critical')
  );
}

export function getChapterById(chapterId: number): OVIQChapter | undefined {
  return OVIQ4_CHAPTERS.find(c => c.id === chapterId);
}

export function getQuestionById(questionId: string): OVIQQuestion | undefined {
  for (const chapter of OVIQ4_CHAPTERS) {
    const question = chapter.questions.find(q => q.id === questionId);
    if (question) return question;
  }
  return undefined;
}

export function getQuestionsForChapter(chapterId: number): OVIQQuestion[] {
  const chapter = getChapterById(chapterId);
  return chapter?.questions || [];
}

